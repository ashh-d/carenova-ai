"""
Conversation logger — opt-in only.

When ENABLE_LOGGING is true, saves timestamped JSON-lines logs that the user
can share with a doctor. Audio is NEVER stored.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

from config import ENABLE_LOGGING, LOG_DIR


def log_turn(
    role: str,
    content: str,
    language: str = "en",
    emergency: bool = False,
    session_id: str = "",
) -> None:
    """Append one conversation turn to the session log file.

    Does nothing if ENABLE_LOGGING is False.
    """
    if not ENABLE_LOGGING:
        return

    log_file = LOG_DIR / f"session_{session_id}.jsonl"
    entry = {
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "role": role,
        "content": content,
        "language": language,
        "emergency": emergency,
    }
    with open(log_file, "a", encoding="utf-8") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")


def generate_summary(session_id: str) -> str:
    """Generate a symptom summary from the session log.

    Returns a markdown-formatted summary the user can show their doctor.
    """
    log_file = LOG_DIR / f"session_{session_id}.jsonl"
    if not log_file.exists():
        return "No conversation log found. Enable logging in settings to use this feature."

    lines = log_file.read_text(encoding="utf-8").strip().split("\n")
    entries = [json.loads(line) for line in lines]

    user_messages = [e for e in entries if e["role"] == "user"]
    if not user_messages:
        return "No messages recorded yet."

    # Build a simple summary
    summary_parts = [
        "## 📋 Symptom Summary for Doctor Visit",
        f"**Date:** {entries[0]['timestamp'][:10]}",
        f"**Messages exchanged:** {len(entries)}",
        "",
        "### What the patient described:",
    ]
    for msg in user_messages:
        summary_parts.append(f"- {msg['content']}")

    summary_parts.extend([
        "",
        "---",
        "*This summary was auto-generated by CareNova AI. "
        "It is not an official medical diagnosis or record.*",
    ])

    return "\n".join(summary_parts)
